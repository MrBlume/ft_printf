#include "ft_printf.h"

void	handler_i(int n)
{
	char	c;

	if (n == -2147483648)
	{
		write(1, "-2147483648", 11);
		return ;
	}
	if (n < 0)
	{
		write(1, "-", 1);
		n = -n;
	}
	if (n > 9)
		handler_i(n / 10);
	c = (n % 10) + '0';
	write(1, &c, 1);
}
